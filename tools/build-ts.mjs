/**
 * `npm run build-ts`: builds dist/ with Vite and types/ with tsc (#741).
 *
 * Vite cannot emit several UMD bundles in one pass, so this runs one `vite build` per
 * bundle, in sequence, with the shared factory in vite.lib.config.mjs. Then
 * `tsc --emitDeclarationOnly` writes types/, with the tsconfig.json settings (D9).
 *
 * `--watch` (`npm run dev-ts`) rebuilds each bundle and the declarations on change. It
 * skips the clean step, so a watch session never leaves dist/ half empty. Note that
 * `dev-ts` is therefore a minified watch build without source maps: it used to be a
 * webpack development build with inline source maps.
 */
import { build } from "vite";
import { spawn } from "node:child_process";
import { copyFileSync, mkdirSync, readdirSync, rmSync } from "node:fs";
import { join, resolve } from "node:path";
import { createRequire } from "node:module";
import { libConfig } from "../vite.lib.config.mjs";

const ROOT = resolve(import.meta.dirname, "..");
const DIST = join(ROOT, "dist");
const VARIANTS = [
  "default",
  "simd",
  "td",
  "node",
  // The tracker facade's worker bundles (#720 D16).
  "worker-default",
  "worker-simd",
  "worker-td",
];
const watch = process.argv.includes("--watch");

/**
 * The files in dist/ that the builds write, or that older webpack builds wrote. dist/ is
 * shared, so emptyOutDir is off and only these are deleted:
 * - the bundles and the pthread worker;
 * - the tracker facade's worker bundles, `NFTTracker*.js` (#720 D16);
 * - the Node ESM entry, regenerated by the build;
 * - webpack leftovers: `*.LICENSE.txt` and the numbered worker chunk
 *   (`602.ARToolkitNFT_td.js`), which would otherwise linger and ship (D8).
 */
function owned(name) {
  return (
    /^ARToolkitNFT.*\.js$/.test(name) ||
    /^NFTTracker.*\.js$/.test(name) ||
    name === "ARToolkitNFT_node.mjs" ||
    name.endsWith(".LICENSE.txt") ||
    /\.ARToolkitNFT_td\.js$/.test(name)
  );
}

function clean() {
  let names;
  try {
    names = readdirSync(DIST);
  } catch (error) {
    // No dist/ yet (a fresh checkout without the committed bundles, or a deleted
    // folder): nothing to clean, and the Vite builds create it. Any other failure
    // (permissions, a file named dist) still stops the build.
    if (error.code === "ENOENT") return;
    throw error;
  }
  for (const name of names) {
    if (owned(name)) rmSync(join(DIST, name));
  }
}

function runTsc() {
  const tsc = createRequire(import.meta.url).resolve("typescript/bin/tsc");
  const args = [tsc, "-p", "tsconfig.json", "--emitDeclarationOnly"];
  if (watch) args.push("--watch", "--preserveWatchOutput");
  return new Promise((resolvePromise, reject) => {
    const child = spawn(process.execPath, args, {
      cwd: ROOT,
      stdio: "inherit",
    });
    child.on("error", reject);
    child.on("exit", (code) =>
      code === 0
        ? resolvePromise()
        : reject(new Error(`tsc exited with code ${code}`)),
    );
  });
}

if (!watch) clean();

for (const variant of VARIANTS) {
  console.log(`vite build: ${variant}`);
  // In watch mode (Vite 8) build() resolves with a watcher as soon as watching starts,
  // not after the first build, so the loop goes on to the next bundle and all seven
  // keep watching.
  await build(libConfig(variant, { watch }));
}

/**
 * The Node ESM entry (#577, D7): a hand-written wrapper over the CJS bundle, copied
 * unchanged, with its declarations. Copying does not read the CJS file, so it does not
 * matter that in watch mode build() resolves before the first build has finished (the
 * wrapper only imports ARToolkitNFT_node.js at run time). tsc does not clean types/, so
 * copying before it is safe, and in watch mode (where tsc never exits) the copy still
 * happens.
 */
copyFileSync(
  join(ROOT, "src-esm/index_node.mjs"),
  join(DIST, "ARToolkitNFT_node.mjs"),
);
mkdirSync(join(ROOT, "types/src"), { recursive: true });
copyFileSync(
  join(ROOT, "src-esm/index_node.d.mts"),
  join(ROOT, "types/src/index_node.d.mts"),
);

console.log("tsc: types/");
await runTsc();
